#!/bin/bash

###############################################################################
# Claude Complete Backup
###############################################################################

set -e

BACKUP_DIR="$HOME/Claude_Backup_$(date +%F_%H-%M-%S)"

mkdir -p "$BACKUP_DIR"

echo "Creating backup at"

echo "$BACKUP_DIR"

backup_if_exists() {

if [ -e "$1" ]; then

echo "Backing up $1"

cp -a "$1" "$BACKUP_DIR"

fi

}

################################################################################
# Claude Desktop
################################################################################

backup_if_exists "$HOME/.claude"

backup_if_exists "$HOME/.config/Claude"

backup_if_exists "$HOME/.config/claude"

backup_if_exists "$HOME/.config/Claude Code"

backup_if_exists "$HOME/.config/Claude-Code"

################################################################################
# Claude CLI
################################################################################

backup_if_exists "$HOME/.claude.json"

backup_if_exists "$HOME/.claude-code"

backup_if_exists "$HOME/.config/claude-code"

backup_if_exists "$HOME/.config/claude"

################################################################################
# MCP
################################################################################

backup_if_exists "$HOME/.mcp"

backup_if_exists "$HOME/.config/mcp"

################################################################################
# API Keys
################################################################################

cp ~/.bashrc "$BACKUP_DIR/" 2>/dev/null || true

cp ~/.profile "$BACKUP_DIR/" 2>/dev/null || true

cp ~/.zshrc "$BACKUP_DIR/" 2>/dev/null || true

################################################################################
# Git
################################################################################

cp ~/.gitconfig "$BACKUP_DIR/" 2>/dev/null || true

################################################################################
# SSH
################################################################################

backup_if_exists "$HOME/.ssh"

################################################################################
# npm
################################################################################

backup_if_exists "$HOME/.npmrc"

################################################################################
# Cursor
################################################################################

backup_if_exists "$HOME/.config/Cursor"

################################################################################
# VSCode
################################################################################

backup_if_exists "$HOME/.config/Code"

################################################################################
# Compress
################################################################################

tar czf "${BACKUP_DIR}.tar.gz" -C "$HOME" "$(basename "$BACKUP_DIR")"

rm -rf "$BACKUP_DIR"

echo

echo "Backup Complete"

echo "${BACKUP_DIR}.tar.gz"
